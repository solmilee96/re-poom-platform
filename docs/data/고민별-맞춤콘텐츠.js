var CONCERN_SPECIFIC = {};

/**
 * 고민×기질 맞춤 콘텐츠 조회 함수
 * @param {string} concernKey - sleep | eating | tantrum | aggression | clothing
 * @param {string} temperamentType - 섬세파 | 에너자이저 | 신중파 | 탐험가 | 순둥이 | 혼합형 | 밸런서
 * @param {string} name - 아이 이름
 * @param {string} age - 아이 나이 (예: "1살 8개월")
 * @returns {{ script: string, practicalTips: Array, realExamples: Array } | null}
 */
function getConcernContent(concernKey, temperamentType, name, age) {
  var concern = CONCERN_SPECIFIC[concernKey];
  if (!concern) return null;
  var data = concern[temperamentType] || concern['_default'];
  if (!data) return null;
  var n = name || '아이';
  var a = age || '';
  function r(s) { return s.replace(/\{name\}/g, n).replace(/\{age\}/g, a); }
  function rArr(arr) {
    return arr.map(function(item) {
      var out = {};
      Object.keys(item).forEach(function(k) {
        out[k] = typeof item[k] === 'string' ? r(item[k]) : item[k];
      });
      return out;
    });
  }
  return {
    script: r(data.script),
    practicalTips: rArr(data.tips),
    realExamples: rArr(data.examples)
  };
}

